// Direct Form II Transposed IIR filter
static void filterIIR(const double* b, size_t b_len,
                      const double* a, size_t a_len,
                      const std::vector<double>& x,
                      std::vector<double>& y) {
    const size_t n = x.size();
    y.resize(n);
    if (n == 0) return;

    const size_t order = std::max(b_len, a_len);
    double z[16] = {0.0};
    const double a0 = a[0];

    for (size_t i = 0; i < n; ++i) {
        const double xi = x[i];
        const double yi = (b[0] * xi + z[0]) / a0;
        y[i] = yi;

        for (size_t k = 0; k + 1 < order - 1; ++k) {
            const double b_val = (k + 1 < b_len) ? b[k + 1] : 0.0;
            const double a_val = (k + 1 < a_len) ? a[k + 1] : 0.0;
            z[k] = b_val * xi - a_val * yi + z[k + 1];
        }
        if (order > 1) {
            const size_t last_idx = order - 2;
            const double b_last = (last_idx + 1 < b_len) ? b[last_idx + 1] : 0.0;
            const double a_last = (last_idx + 1 < a_len) ? a[last_idx + 1] : 0.0;
            z[last_idx] = b_last * xi - a_last * yi;
        }
    }
}

