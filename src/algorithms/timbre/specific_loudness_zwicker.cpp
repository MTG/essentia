void SpecificLoudnessZwicker::computeThirdOctaveLevels(const std::vector<Real>& audioFrame,
                                                     std::vector<Real>& bandLevels,
                                                     Real pRef) {
    bandLevels.assign(28, -std::numeric_limits<Real>::infinity());
    const size_t initial_len = audioFrame.size();
    if (initial_len == 0) return;

    std::vector<double> x(initial_len);
    for (size_t i = 0; i < initial_len; ++i) {
        x[i] = static_cast<double>(audioFrame[i]);
    }

    std::vector<double> y;
    y.reserve(initial_len);

    auto computeRmsSpl = [](const std::vector<double>& signal) -> double {
        const size_t m = signal.size();
        if (m == 0) return -std::numeric_limits<double>::infinity();
        double max_val = 0.0;
        double sum_sq = 0.0;
        for (double val : signal) {
            if (val > max_val) max_val = val;
            sum_sq += val * val;
        }
        if (max_val > 0.0 && sum_sq > 0.0) {
            double rms = std::sqrt(sum_sq / static_cast<double>(m));
            return 20.0 * std::log10(rms);
        }
        return -std::numeric_limits<double>::infinity();
    };

    // Bands 27 down to 24 (>= 6300 Hz): direct filtering
    filterIIR(BUTTERWORTH_27_B, 9, BUTTERWORTH_27_A, 9, x, y);
    bandLevels[27] = static_cast<Real>(computeRmsSpl(y) + static_cast<double>(pRef));

    filterIIR(BUTTERWORTH_26_B, 9, BUTTERWORTH_26_A, 9, x, y);
    bandLevels[26] = static_cast<Real>(computeRmsSpl(y) + static_cast<double>(pRef));

    filterIIR(BUTTERWORTH_25_B, 9, BUTTERWORTH_25_A, 9, x, y);
    bandLevels[25] = static_cast<Real>(computeRmsSpl(y) + static_cast<double>(pRef));

    filterIIR(BUTTERWORTH_24_B, 9, BUTTERWORTH_24_A, 9, x, y);
    bandLevels[24] = static_cast<Real>(computeRmsSpl(y) + static_cast<double>(pRef));

    // Bands 23 down to 2 (<= 5000 Hz): multirate downsampling
    std::vector<double> x_filtered;
    x_filtered.reserve(initial_len);

    for (int i = 23; i > 1; i -= 3) {
        filterIIR(CHEBYSHEV_AA_B, 3, CHEBYSHEV_AA_A, 3, x, x_filtered);
        const size_t downsampled_len = x_filtered.size() / 2;
        if (downsampled_len == 0) break;

        x.resize(downsampled_len);
        for (size_t j = 0; j < downsampled_len; ++j) {
            x[j] = x_filtered[2 * j + 1];
        }

        filterIIR(BUTTERWORTH_26_B, 9, BUTTERWORTH_26_A, 9, x, y);
        bandLevels[i] = static_cast<Real>(computeRmsSpl(y) + static_cast<double>(pRef));

        filterIIR(BUTTERWORTH_25_B, 9, BUTTERWORTH_25_A, 9, x, y);
        bandLevels[i - 1] = static_cast<Real>(computeRmsSpl(y) + static_cast<double>(pRef));

        filterIIR(BUTTERWORTH_24_B, 9, BUTTERWORTH_24_A, 9, x, y);
        bandLevels[i - 2] = static_cast<Real>(computeRmsSpl(y) + static_cast<double>(pRef));
    }
}

void SpecificLoudnessZwicker::compute(const std::vector<Real>& audioFrame,
                                     Real& totalLoudness,
                                     std::vector<Real>& specificLoudness,
                                     Real pRef,
                                     int mode) {
    std::vector<Real> bandLevels(28);
    computeThirdOctaveLevels(audioFrame, bandLevels, pRef);

    // Low-frequency equal-loudness contour corrections (first 11 bands)
    double Ti[11] = {0.0};
    for (int i = 0; i < 11; ++i) {
        const double Pi = static_cast<double>(bandLevels[i]);
        int j = 0;
        while (j < 7 && Pi > (RAP_TABLE[j] - DLL_TABLE[j][i])) {
            j++;
        }
        double Xp = Pi + DLL_TABLE[j][i];
        Ti[i] = std::pow(10.0, Xp / 10.0);
    }

    // Group into first 3 critical bands (LCB)
    double Gi[3];
    Gi[0] = Ti[0] + Ti[1] + Ti[2] + Ti[3] + Ti[4] + Ti[5];
    Gi[1] = Ti[6] + Ti[7] + Ti[8];
    Gi[2] = Ti[9] + Ti[10];

    double LCB[3];
    for (int k = 0; k < 3; ++k) {
        LCB[k] = (Gi[k] > 0.0) ? (10.0 * std::log10(std::max(Gi[k], 1e-12))) : 0.0;
    }

    // Main loudness in 20 critical bands (Nm)
    double Nm[21] = {0.0};
    for (int i = 0; i < 20; ++i) {
        double Le = (i <= 2) ? LCB[i] : static_cast<double>(bandLevels[i + 8]);
        double Lk = Le - A0_TABLE[i];
        if (mode == 1) {
            Le += DDF_TABLE[i];
        }
        if (Le > LTQ_TABLE[i]) {
            Le = Lk - DCB_TABLE[i];
            const double S = 0.25;
            double MP1 = 0.0635 * std::pow(10.0, 0.025 * LTQ_TABLE[i]);
            double MP2 = std::pow(1.0 - S + S * std::pow(10.0, 0.1 * (Le - LTQ_TABLE[i])), 0.25) - 1.0;
            Nm[i] = std::max(0.0, MP1 * MP2);
        }
    }

    double KORRY = std::min(1.0, 0.4 + 0.32 * std::pow(Nm[0], 0.2));
    Nm[0] *= KORRY;

    // Masking curve spread across 240 Bark bins (0.1 Bark step, 0.1 to 24.0 Bark)
    double N = 0.0;
    double z1 = 0.0;
    double n1 = 0.0;
    int j = 17;
    int iz = 0;
    double z = 0.1;
    std::vector<double> ns;
    ns.reserve(256);

    for (int i = 0; i < 21; ++i) {
        const int ig = (i == 0) ? 7 : std::min(i - 1, 7);
        int control = 1;

        while ((z1 < ZUP_TABLE[i]) || (control == 1)) {
            if (n1 < Nm[i]) {
                j = 0;
                while (j < 18 && RNS_TABLE[j] > Nm[i]) {
                    j++;
                }
            }

            if (n1 <= Nm[i]) {
                const double z2 = ZUP_TABLE[i];
                const double n2 = Nm[i];
                N += n2 * (z2 - z1);

                const int int_start = static_cast<int>(std::round(z * 10.0));
                const int int_end = static_cast<int>(std::round(z2 * 10.0));
                for (int k_idx = int_start; k_idx <= int_end; ++k_idx) {
                    if (iz == static_cast<int>(ns.size())) {
                        ns.push_back(n2);
                    } else if (iz < static_cast<int>(ns.size())) {
                        ns[iz] = n2;
                    }
                    if (k_idx < int_end) {
                        iz++;
                    }
                }
                z = int_end * 0.1;

                if (n2 == RNS_TABLE[j]) {
                    j = std::min(17, j + 1);
                }
                n1 = n2;
                z1 = std::round(z2 * 10.0) * 0.1;
                control++;
            } else {
                double n2 = std::max(Nm[i], RNS_TABLE[j]);
                double dz = (n1 - n2) / USL_TABLE[j][ig];
                dz = std::max(0.1, std::round(dz * 10.0) * 0.1);
                double z2 = z1 + dz;
                if (z2 > ZUP_TABLE[i]) {
                    z2 = ZUP_TABLE[i];
                    dz = z2 - z1;
                    n2 = n1 - dz * USL_TABLE[j][ig];
                }
                N += dz * (n1 + n2) / 2.0;

                const int int_start = static_cast<int>(std::round(z * 10.0));
                const int int_end = static_cast<int>(std::round(z2 * 10.0));
                for (int k_idx = int_start; k_idx <= int_end; ++k_idx) {
                    const double k_val = k_idx * 0.1;
                    const double val = n1 - (k_val - z1) * USL_TABLE[j][ig];
                    if (iz == static_cast<int>(ns.size())) {
                        ns.push_back(val);
                    } else if (iz < static_cast<int>(ns.size())) {
                        ns[iz] = val;
                    }
                    if (k_idx < int_end) {
                        iz++;
                    }
                }
                z = int_end * 0.1;

                if (n2 == RNS_TABLE[j]) {
                    j = std::min(17, j + 1);
                }
                n1 = n2;
                z1 = std::round(z2 * 10.0) * 0.1;
                control++;
            }
        }
    }

    N = std::max(0.0, N);
    totalLoudness = static_cast<Real>(N);

    specificLoudness.resize(240);
    const size_t ns_len = ns.size();
    for (size_t k = 0; k < 240; ++k) {
        if (k < ns_len) {
            specificLoudness[k] = static_cast<Real>(ns[k]);
        } else if (ns_len > 0) {
            specificLoudness[k] = static_cast<Real>(ns[ns_len - 1]);
        } else {
            specificLoudness[k] = 0.0f;
        }
    }
}

Real SpecificLoudnessZwicker::computeSharpnessFastl(const std::vector<Real>& specificLoudness) {
    const size_t n = specificLoudness.size();
    if (n == 0) return 0.0f;

    double num = 0.0;
    double den = 0.0;

    for (size_t k = 0; k < n; ++k) {
        const double val = static_cast<double>(specificLoudness[k]);
        const double z = (static_cast<double>(k) + 1.0) * 0.1;
        double gz = 1.0;
        if (k >= 140) {
            gz = 0.00012 * std::pow(z, 4.0)
               - 0.0056  * std::pow(z, 3.0)
               + 0.1     * std::pow(z, 2.0)
               - 0.81    * z
               + 3.5;
        }
        num += val * gz * z * 0.1;
        den += val * 0.1;
    }

    if (den <= 0.0) {
        return 0.0f;
    }
    return static_cast<Real>(0.11 * (num / den));
}

void SpecificLoudnessZwicker::computeBoominessMetrics(const std::vector<Real>& specificLoudness,
                                                     Real& frameBoomingIndex,
                                                     Real& lowBarkEnergy) {
    const size_t n = specificLoudness.size();
    if (n == 0) {
        frameBoomingIndex = 0.0f;
        lowBarkEnergy = 0.0f;
        return;
    }

    double total_loudness = 0.0;
    for (size_t k = 0; k < n; ++k) {
        total_loudness += static_cast<double>(specificLoudness[k]);
    }

    double low_bark_sum = 0.0;
    const size_t w70_limit = std::min(n, static_cast<size_t>(70));
    for (size_t k = 0; k < w70_limit; ++k) {
        low_bark_sum += BOOM_WEIGHT_70_TABLE[k] * static_cast<double>(specificLoudness[k]);
    }
    lowBarkEnergy = static_cast<Real>(low_bark_sum);

    if (total_loudness <= 0.0) {
        frameBoomingIndex = 0.0f;
        return;
    }

    // Energy below 280 Hz
    double ll = 0.0;
    const size_t below_280_limit = std::min(n, static_cast<size_t>(27));
    for (size_t k = 0; k < below_280_limit; ++k) {
        ll += static_cast<double>(specificLoudness[k]);
    }

    double bandsum_acc = 0.0;
    const size_t boom_limit = std::min(n, static_cast<size_t>(240));
    for (size_t k = 0; k < boom_limit; ++k) {
        double weighted_i = static_cast<double>(specificLoudness[k]) * BOOM_WEIGHTING_TABLE[k];
        bandsum_acc += std::pow(10.0, weighted_i / 10.0);
    }

    double bandsum = 10.0 * std::log10(bandsum_acc + 1e-12);
    frameBoomingIndex = static_cast<Real>(bandsum * (ll / total_loudness));
}

void SpecificLoudnessZwicker::computeWarmthRegionLevels(const std::vector<Real>& specificLoudness,
                                                       Real& warmthRegionLevel,
                                                       Real& highFreqLevel) {
    const size_t n = specificLoudness.size();
    double wr_acc = 0.0;
    if (n > 10) {
        const size_t wr_end = std::min(n, static_cast<size_t>(40));
        for (size_t k = 10; k < wr_end; ++k) {
            wr_acc += WARMTH_REGION_TABLE[k - 10] * static_cast<double>(specificLoudness[k]);
        }
    }
    warmthRegionLevel = static_cast<Real>(wr_acc);

    double hf_acc = 0.0;
    if (n > 80) {
        const size_t hf_end = std::min(n, static_cast<size_t>(240));
        for (size_t k = 80; k < hf_end; ++k) {
            hf_acc += WARMTH_HF_TABLE[k - 80] * static_cast<double>(specificLoudness[k]);
        }
    }
    highFreqLevel = static_cast<Real>(hf_acc);
}

Real SpecificLoudnessZwicker::computeHardnessMidbandLevel(const std::vector<Real>& specificLoudness) {
    const size_t n = specificLoudness.size();
    double midband_acc = 0.0;
    if (n > 70) {
        const size_t mid_end = std::min(n, static_cast<size_t>(140));
        for (size_t k = 70; k < mid_end; ++k) {
            midband_acc += HARDNESS_MIDBAND_TABLE[k - 70] * static_cast<double>(specificLoudness[k]);
        }
    }
    return static_cast<Real>(midband_acc);
}

